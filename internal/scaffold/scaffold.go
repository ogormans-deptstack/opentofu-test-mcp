// Package scaffold inspects an OpenTofu/Terraform module and generates starter
// test artifacts: a .tftest.hcl skeleton and mock_provider blocks.
package scaffold

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclparse"
)

// Variable is a module input variable.
type Variable struct {
	Name     string `json:"name"`
	Required bool   `json:"required"`
}

// Module is the inspected surface of a module directory.
type Module struct {
	Variables []Variable `json:"variables"`
	Outputs   []string   `json:"outputs"`
	Providers []string   `json:"providers"`
}

var moduleSchema = &hcl.BodySchema{
	Blocks: []hcl.BlockHeaderSchema{
		{Type: "variable", LabelNames: []string{"name"}},
		{Type: "output", LabelNames: []string{"name"}},
		{Type: "provider", LabelNames: []string{"name"}},
		{Type: "terraform"},
	},
}

var variableSchema = &hcl.BodySchema{
	Attributes: []hcl.AttributeSchema{{Name: "default"}},
}

// Inspect parses every .tf file in dir and collects variables, outputs, and
// provider names. Parse errors on individual files are skipped so a partially
// valid module can still be scaffolded.
func Inspect(dir string) (*Module, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("reading module dir: %w", err)
	}

	parser := hclparse.NewParser()
	mod := &Module{}
	seenProvider := map[string]bool{}

	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".tf") || strings.HasSuffix(e.Name(), ".tftest.tf") {
			continue
		}
		file, diags := parser.ParseHCLFile(filepath.Join(dir, e.Name()))
		if diags.HasErrors() || file == nil {
			continue
		}
		content, _, _ := file.Body.PartialContent(moduleSchema)
		for _, block := range content.Blocks {
			switch block.Type {
			case "variable":
				v := Variable{Name: block.Labels[0], Required: true}
				attrs, _, _ := block.Body.PartialContent(variableSchema)
				if _, ok := attrs.Attributes["default"]; ok {
					v.Required = false
				}
				mod.Variables = append(mod.Variables, v)
			case "output":
				mod.Outputs = append(mod.Outputs, block.Labels[0])
			case "provider":
				if !seenProvider[block.Labels[0]] {
					seenProvider[block.Labels[0]] = true
					mod.Providers = append(mod.Providers, block.Labels[0])
				}
			}
		}
	}

	sort.Slice(mod.Variables, func(i, j int) bool { return mod.Variables[i].Name < mod.Variables[j].Name })
	sort.Strings(mod.Outputs)
	sort.Strings(mod.Providers)
	return mod, nil
}

// TestFile renders a .tftest.hcl skeleton for the module. command is "plan" or
// "apply"; mock controls whether mock_provider stubs are emitted for the
// module's providers.
func TestFile(mod *Module, command string, mock bool) string {
	if command != "plan" && command != "apply" {
		command = "plan"
	}
	var sb strings.Builder
	sb.WriteString("# Starter test generated by opentofu-test-mcp.\n")
	sb.WriteString("# Replace the TODO values and tighten the assertions before committing.\n\n")

	if mock {
		for _, p := range mod.Providers {
			fmt.Fprintf(&sb, "mock_provider %q {}\n\n", p)
		}
	}

	var required []Variable
	for _, v := range mod.Variables {
		if v.Required {
			required = append(required, v)
		}
	}
	if len(required) > 0 {
		sb.WriteString("variables {\n")
		for _, v := range required {
			fmt.Fprintf(&sb, "  %s = null # TODO: required input\n", v.Name)
		}
		sb.WriteString("}\n\n")
	}

	fmt.Fprintf(&sb, "run %q {\n", "defaults")
	fmt.Fprintf(&sb, "  command = %s\n", command)
	if len(mod.Outputs) == 0 {
		sb.WriteString("\n  # TODO: add assert blocks that check this module's behavior.\n")
	}
	for _, o := range mod.Outputs {
		sb.WriteString("\n  assert {\n")
		fmt.Fprintf(&sb, "    condition     = output.%s != null\n", o)
		fmt.Fprintf(&sb, "    error_message = %q\n", fmt.Sprintf("output %s should be set", o))
		sb.WriteString("  }\n")
	}
	sb.WriteString("}\n")
	return sb.String()
}
